// Unique list of municipalities
export const MUNICIPALITIES = Array.from(new Set(BARANGAY_FACILITY_DATA.map(d => d.municipality)));

// Helper to get all barangays grouped by municipality
export const BARANGAYS_BY_MUNICIPALITY: Record<string, string[]> = BARANGAY_FACILITY_DATA.reduce((acc, curr) => {
  if (!acc[curr.municipality]) acc[curr.municipality] = [];
  if (!acc[curr.municipality].includes(curr.barangay)) acc[curr.municipality].push(curr.barangay);
  return acc;
}, {} as Record<string, string[]>);

// Helper to get facilities for a specific municipality and barangay
export function getFacilitiesForBarangay(municipality: string, barangay: string): string[] {
  const match = BARANGAY_FACILITY_DATA.find(
    d => d.municipality.toLowerCase() === municipality.toLowerCase() && d.barangay.toLowerCase() === barangay.toLowerCase()
  );
  if (match) return match.facilities;
  // If only barangay matches
  const bMatch = BARANGAY_FACILITY_DATA.find(d => d.barangay.toLowerCase() === barangay.toLowerCase());
  return bMatch ? bMatch.facilities : [];
}

// Helper to find the barangay & municipality for an existing facility value
export function findLocationForFacility(facilityName: string): { municipality: string; barangay: string } | null {
  if (!facilityName) return null;
  for (const item of BARANGAY_FACILITY_DATA) {
    if (item.facilities.includes(facilityName)) {
      return { municipality: item.municipality, barangay: item.barangay };
    }
  }
  return null;
}

