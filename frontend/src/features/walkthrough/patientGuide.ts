export function patientTabStep(step: WalkthroughStep, selector: string, tabKey: string): WalkthroughStep {
  const activateSelector = `[data-walkthrough="${selector}"]`;
  return {
    ...step,
    activateSelector,
    tabKey,
    content: `${step.content} Next will explain each available action in this tab before moving on.`,
    actions: PATIENT_REGISTRATION_ACTION_DEFS.map(([key, title, content]) => ({
      id: `${step.id}-${key}`,
      module: step.module,
      route: step.route,
      title,
      content,
      placement: 'auto',
      tabKey,
      activateSelector,
      actionStep: true,
      targetSelector: `[data-patient-action="${key}"]`,
    })),
  };
}

export function expandPatientSteps(steps: WalkthroughStep[], snapshots: Record<string, string[]> = {}) {
  return steps.flatMap(step => {
    if (!step.actions || step.actions.length === 0) return [step];
    return [step, ...step.actions.filter(action => snapshots[step.id]?.includes(action.id))];
  });
}

export function availablePatientActions(step: WalkthroughStep): string[] {
  return (step.actions || []).filter(action => Array.from(document.querySelectorAll<HTMLElement>(action.targetSelector)).some(element => {
    const style = getComputedStyle(element);
    return element.getClientRects().length > 0 && style.visibility !== 'hidden' && style.display !== 'none';
  })).map(action => action.id);
}
